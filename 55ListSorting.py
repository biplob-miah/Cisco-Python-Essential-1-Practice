#this program shows uses of sorting in a list
numbers  = [4,99,1, 73, 55]
numbers.sort() #sort function organize list elements ascending(smaller to greatr)
print("Using sort function :",numbers)

numbers.sort(reverse=True) #sort function with reverse=True arg organize list element descending(greater to smaller)

print("Using sort function with argument :",numbers)

numbers.reverse()
print("Using reverse function :",numbers)
