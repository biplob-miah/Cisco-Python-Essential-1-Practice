#this program shows how we pass arguments in a functions parameter with positions
def intro(first_name, last_name): #first_name and last_name is the parameter here
    print("My first name is", first_name, "and my last name is", last_name)
intro("David", "Anderson") #passing the argument to the function parameter with positions
intro("Kendy", "Arthur")
#what if we want to change the Ashley Parker name as Parker ashely?
intro("Parker", "Ashely in Hungarian culture")


